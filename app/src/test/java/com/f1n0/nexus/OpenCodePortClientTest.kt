package com.f1n0.nexus

import okhttp3.mockwebserver.MockResponse
import okhttp3.mockwebserver.MockWebServer
import org.junit.Assert.assertEquals
import org.junit.Test

class OpenCodePortClientTest {
    @Test
    fun `sends OpenCode's actual Basic Auth identity on the wire`() {
        MockWebServer().use { server ->
            server.enqueue(MockResponse().setResponseCode(200).setBody("{}"))
            server.start()

            val response = OpenCodePortClient(server.url("v1/execute").toString(), "test-token")
                .postJson("{\"prompt\":\"ping\"}")

            val request = requireNotNull(server.takeRequest())
            assertEquals("{}", response)
            assertEquals("POST", request.method)
            assertEquals("/v1/execute", request.path)
            // Literal wire value independently checks the documented fork contract;
            // it is deliberately not generated by the production Credentials call.
            assertEquals("Basic b3BlbmNvZGU6dGVzdC10b2tlbg==", request.getHeader("Authorization"))
        }
    }
}
